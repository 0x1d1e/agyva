#!/usr/bin/env bash
# Produce a text capture and an SVG frame of the interactive view, from a
# SYNTHETIC sandbox (fake accounts, fake agy, scratch HOME; see
# demo-sandbox.sh). The result is not a recording of anyone's real accounts or
# quota.
#
#   scripts/capture-tui.sh [output-file]    # default: docs/tui-capture.txt
#
# The SVG is written next to the text capture: docs/tui.svg by default, or
# <output-file without .txt>.svg. Needs tmux and python3. Uses a private tmux
# server (-L), never your own sessions.
set -euo pipefail

here=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
if [ $# -ge 1 ]; then
  out=$1
  case "$out" in
    *.svg) svg=$out; out=${out%.svg}.txt ;;
    *) svg=${out%.txt}.svg ;;
  esac
else
  out=$here/docs/tui-capture.txt
  svg=$here/docs/tui.svg
fi
command -v tmux >/dev/null || { echo "tmux is required for capture-tui.sh" >&2; exit 1; }
command -v python3 >/dev/null || { echo "python3 is required for capture-tui.sh" >&2; exit 1; }
bin=${AGYVA_BIN:-}
if [ -z "$bin" ]; then
  for c in "$here/target/release/agyva" "$here/target/debug/agyva"; do
    [ -x "$c" ] && bin=$c && break
  done
fi

work=$(mktemp -d)
sock=agyva-capture-$$
cleanup() { tmux -L "$sock" kill-server 2>/dev/null || true; rm -rf "$work"; }
trap cleanup EXIT

AGYVA_BIN=$bin "$here/scripts/demo-sandbox.sh" "$work/sb" > "$work/env.sh"

run="env -i PATH=/usr/bin:/bin TERM=xterm-256color LANG=C.UTF-8 NO_COLOR=1"
while IFS= read -r line; do
  line=${line#export }
  eval "kv=$(printf '%q' "${line%%=*}")=${line#*=}"   # strips the quotes
  run+=" $(printf '%q' "$kv")"
done < <(grep '^export ' "$work/env.sh")
run+=" $(printf '%q' "$bin")"

tmux -L "$sock" new-session -d -x 96 -y 26 "$run"
snap() { tmux -L "$sock" capture-pane -p; }
wait_for() { # text
  for _ in $(seq 1 100); do snap | grep -q -- "$1" && return 0; sleep 0.1; done
  echo "timed out waiting for: $1" >&2; snap >&2; exit 1
}

{
  echo "SYNTHETIC CAPTURE: fake accounts (example.invalid), a fake agy script and made-up"
  echo "quota numbers, generated by scripts/capture-tui.sh. Not real data."
  echo
  wait_for "alice"
  sleep 0.5
  echo '--- agyva (main view) ---'
  snap
  tmux -L "$sock" send-keys j
  sleep 0.3
  tmux -L "$sock" send-keys d
  wait_for "Details"
  echo
  echo '--- d: details for the selected account ---'
  snap
  tmux -L "$sock" send-keys Escape
  sleep 0.2
  tmux -L "$sock" send-keys '?'
  wait_for "Help"
  echo
  echo '--- ?: help ---'
  snap
} | sed -e 's/[[:space:]]*$//' | cat -s > "$out"
tmux -L "$sock" send-keys Escape q 2>/dev/null || true

# Turn the first frame into a self-contained SVG. The UI text is used verbatim
# (no redrawing, no invented numbers); only the surrounding terminal chrome and
# the SYNTHETIC label are added.
python3 -I - "$out" "$svg" <<'PY'
import html
import sys

text_path, svg_path = sys.argv[1:3]
with open(text_path, encoding="utf-8") as fh:
    lines = fh.read().splitlines()
start = lines.index("--- agyva (main view) ---") + 1
frame = []
for line in lines[start:]:
    if line.startswith("--- "):
        break
    frame.append(line)
while frame and not frame[-1].strip():
    frame.pop()
width_chars = max(len(line) for line in frame) if frame else 80
char_w, line_h, pad = 7.9, 19, 22
title_h, foot_h = 42, 30
width = round(width_chars * char_w + pad * 2)
height = title_h + len(frame) * line_h + foot_h + pad
body = "\n".join(
    '  <text x="%d" y="%d" class="ui" xml:space="preserve">%s</text>'
    % (pad, title_h + 16 + i * line_h, html.escape(line or " "))
    for i, line in enumerate(frame)
)
style = """
    .bg { fill: #101418; }
    .chrome { fill: #1b2229; }
    .ui { font-family: "JetBrains Mono", "DejaVu Sans Mono", monospace; font-size: 13px; fill: #d7dde3; white-space: pre; }
    .title { font-family: system-ui, sans-serif; font-size: 12px; font-weight: 600; fill: #9aa7b2; }
    .note { font-family: system-ui, sans-serif; font-size: 12px; fill: #e0b64a; }
    .dot { fill: #3c4650; }
""".strip("\n")
svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-labelledby="title desc">
  <title id="title">agyva terminal interface (synthetic sandbox)</title>
  <desc id="desc">SYNTHETIC screenshot: fake example.invalid accounts, a fake agy script and made-up quota numbers. Not a recording of real accounts.</desc>
  <style>
{style}
  </style>
  <rect class="bg" width="100%" height="100%" rx="8"/>
  <rect class="chrome" width="100%" height="{title_h}" rx="8"/>
  <rect class="chrome" y="{title_h - 8}" width="100%" height="8"/>
  <circle class="dot" cx="18" cy="17" r="5"/><circle class="dot" cx="34" cy="17" r="5"/><circle class="dot" cx="50" cy="17" r="5"/>
  <text class="title" x="{width / 2:.0f}" y="21" text-anchor="middle">agyva - synthetic sandbox</text>
{body}
  <text class="note" x="{pad}" y="{height - 16}">SYNTHETIC: fake accounts and made-up quota numbers, generated by scripts/capture-tui.sh</text>
</svg>
"""
with open(svg_path, "w", encoding="utf-8") as fh:
    fh.write(svg)
PY
echo "wrote $out and $svg"
